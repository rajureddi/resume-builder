test('overlapping requests have isolated data and leave their browser snapshots unchanged', async () => {
  const first = snapshot('First Browser');
  const second = snapshot('Second Browser');
  let release;
  const gate = new Promise(resolve => { release = resolve; });
  const one = runWithStudioData(first, async () => {
    await db.saveProfile({ ...await db.getProfile(), title: 'First changed title' });
    await db.createProject({ title: 'First private project', year: '', description: '', tags: [], domains: [], github: '', bullets: [] });
    await gate;
    return { profile: await db.getProfile(), projects: await db.listProjects() };
  });
  const two = runWithStudioData(second, async () => {
    await db.saveProfile({ ...await db.getProfile(), title: 'Second changed title' });
    release();
    return { profile: await db.getProfile(), projects: await db.listProjects() };
  });
  const [a, b] = await Promise.all([one, two]);
  assert.equal(a.profile.name, 'First Browser');
  assert.equal(a.profile.title, 'First changed title');
  assert.equal(b.profile.name, 'Second Browser');
  assert.equal(b.profile.title, 'Second changed title');
  assert.ok(a.projects.some(item => item.title === 'First private project'));
  assert.equal(b.projects.some(item => item.title === 'First private project'), false);
  assert.notEqual(first.profile.title, 'First changed title');
  assert.equal(first.projects.some(item => item.title === 'First private project'), false);
  assert.equal(fs.existsSync(process.env.DATA_FILE), false);
  await assert.rejects(db.saveProfile(first.profile), /request context/);
});

