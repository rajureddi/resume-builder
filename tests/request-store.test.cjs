test('fresh requests cannot read an application generated by an earlier request', async () => {
  const route = require('../app/api/tailor-resume/route.ts');
  const data = snapshot('Private Candidate');
  const generated = await route.POST(request('/api/tailor-resume', { studioData: data, company: 'Example', role: 'Frontend Developer', jdText: 'Build React and TypeScript frontend applications with tested interfaces.' }));
  assert.equal(generated.status, 200);
  const { application } = await generated.json();
  assert.equal(application.profileSnapshot.name, 'Private Candidate');
  assert.equal(data.applications.length, 0);
  const lookup = require('../app/api/applications/[id]/route.ts');
  const res = await lookup.GET(new NextRequest(`http://localhost/api/applications/${application.id}`), { params: Promise.resolve({ id: application.id }) });
  assert.equal(res.status, 404);
  assert.equal(fs.existsSync(process.env.DATA_FILE), false);
});

test('browser-supplied resumes generate matching PDF, DOCX, TXT and layout without a database', async () => {
  const data = snapshot('Browser Export Candidate');
  const app = { ...tailorRules({ company: 'Example', role: 'Frontend Developer', jdText: 'Build React and TypeScript frontend applications.', profile: data.profile, projects: data.projects }), id: 'local-export', status: 'Saved', createdAt: '2026-11-24T00:00:00Z' };
  data.applications = [app];
  const ctx = { params: Promise.resolve({ id: app.id }) };
  const route = require('../app/api/applications/[id]/download/route.ts');
  for (const format of ['pdf', 'docx', 'txt']) {
    const res = await route.POST(request(`/api/applications/${app.id}/download`, { studioData: data, format }), ctx);
    assert.equal(res.status, 200, format);
    assert.match(res.headers.get('Content-Disposition'), new RegExp(`\\.${format}"$`));
    const bytes = Buffer.from(await res.arrayBuffer());
    const text = format === 'pdf' ? (await extractText(new Uint8Array(bytes), { mergePages: true })).text
      : format === 'docx' ? (await mammoth.extractRawText({ buffer: bytes })).value : bytes.toString('utf8');
    assert.ok(text.toLowerCase().includes('browser export candidate'), format);
    assert.ok(text.includes(data.profile.email), format);
  }
  const layoutRoute = require('../app/api/applications/[id]/layout/route.ts');
  const layoutResponse = await layoutRoute.POST(request(`/api/applications/${app.id}/layout`, { studioData: data }), ctx);
  assert.equal(layoutResponse.status, 200);
  const { layout } = await layoutResponse.json();
  assert.ok(layout.pages.flatMap(page => page.items).some(item => item.kind === 'text' && item.text === data.profile.name.toUpperCase()));
  assert.equal((await route.POST(request(`/api/applications/${app.id}/download`, { format: 'txt' }), ctx)).status, 400);
  assert.equal((await route.GET()).status, 405);
  assert.equal(fs.existsSync(process.env.DATA_FILE), false);
});

